  Gender: String,
  Age: Number,
  'FIR/Case No': String,
  'PS Name': String,
  'Prisoner Alias Name': String,
  'Mother Name': String,
  'Spouse Name': String,
  'Permanent Address': String,
  PermtDistrict: String,
  PermtState: String,
  'Present Address': String,
  PresentDistrict: String,
  PresentState: String,
  'Jail Name': String,
  'Prisoner Type': String,
  Ward: String,
  Barrack: String,
  RegisterNo: String,
  'Period Undergone(Days)': Number,
  'First Admission Date': String,
  'Latest Admission Date': String,
  'Release Date': String,
  Tendency: String,
  ImprisonmentType: String,
  Occupation: String,
  'Duty Point': String,
  'Relative Contact': String,
  Religion: String,
  Case_Type: String,
  '14-Digit FIR No': String,
  'CNR No': { type: String, index: true },
  'PTN No': String,
  'Case SNO': Number,
  'Case Year': Number,
  'FIR SNo': String,
  'FIR Year': Number,
  'Case No.': String,
  'Act Section': String,
  'FIR Date': String,
  'Court Name': String,
  'Judge Name': String,
